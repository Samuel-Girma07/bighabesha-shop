// 2. Standardized Error Taxonomy (RFC 7807 Problem Details)
// ============================================================================

/**
 * Standardized Machine-Readable Error Codes
 */
export type VerificationFailureCode =
  | 'RECEIPT_ALREADY_USED'       // 409 Conflict: Transaction reference already matched
  | 'BENEFICIARY_MISMATCH'        // 422 Unprocessable: Transfer was sent to unauthorized account
  | 'AMOUNT_MISMATCH'             // 422 Unprocessable: Amount verified is less than net payable
  | 'RECEIPT_EXPIRED'             // 422 Unprocessable: Timestamp outside acceptable temporal window
  | 'QR_DECODE_FAILED'            // 422 Unprocessable: Image could not be decoded to QR matrix
  | 'BANK_PORTAL_UNAVAILABLE'     // 504 Gateway Timeout: Upstream bank connection timed out / reset
  | 'PORTAL_GEOBLOCKED'           // 502 Bad Gateway: Upstream gateway blocked non-Ethiopian egress
  | 'UNSUPPORTED_BANK'            // 400 Bad Request: Rail or format not supported by automated engine
  | 'CORRUPTED_FILE'              // 400 Bad Request: Magic byte validation or image parsing failed
  | 'RATE_LIMITED'                // 429 Too Many Requests: Rate limit exceeded for verification
  | 'INTERNAL_ENGINE_ERROR';      // 500 Internal Server Error: Unexpected runtime failure

/**
 * RFC 7807 Problem Details Specification Schema
 * @see https://datatracker.ietf.org/doc/html/rfc7807
 */
export interface Rfc7807ProblemDetails {
  /** URI identifier that categorizes the problem type */
  type: string;
  /** Short, human-readable summary of the problem type */
  title: string;
  /** The HTTP status code generated by the origin server */
  status: number;
  /** Human-readable explanation specific to this occurrence of the problem */
  detail: string;
  /** Relative URI reference identifying the specific occurrence */
  instance: string;
  /** Application-specific standardized error code */
  code: VerificationFailureCode;
  /** Structured diagnostic context regarding the failure */
  details?: Record<string, unknown>;
  /** Concrete guidance to help the client or operator resolve the condition */
  remediation_hint: string;
  /** Timestamp when the failure occurred in ISO 8601 format */
  timestamp: string;
}

/**
 * Base domain exception for receipt verification errors conforming to RFC 7807.
 */
export class ReceiptVerificationError extends Error {
  public readonly problemDetails: Rfc7807ProblemDetails;

  constructor(
    code: VerificationFailureCode,
    status: number,
    title: string,
    detail: string,
    remediation_hint: string,
    instance: string = '/api/receipts/verify',
    details?: Record<string, unknown>
  ) {
    super(detail);
    this.name = 'ReceiptVerificationError';
    this.problemDetails = {
      type: `https://bighabesha.shop/errors/${code.toLowerCase().replace(/_/g, '-')}`,
      title,
      status,
      detail,
      instance,
      code,
      details,
      remediation_hint,
      timestamp: new Date().toISOString(),
    };
  }
}

export class ReceiptAlreadyUsedError extends ReceiptVerificationError {
  constructor(reference: string, existingOrderId?: string, instance?: string) {
    super(
      'RECEIPT_ALREADY_USED',
      409,
      'Receipt Already Used',
      `Transaction reference '${reference}' has already been verified and credited to another order.`,
      'This transfer receipt has already been used. Please submit the receipt for your current payment or contact support.',
      instance,
      { reference, existingOrderId }
    );
    this.name = 'ReceiptAlreadyUsedError';
  }
}

export class BeneficiaryMismatchError extends ReceiptVerificationError {
  constructor(bank: SupportedBank, actualBeneficiary: string, expectedAccounts: string[], instance?: string) {
    super(
      'BENEFICIARY_MISMATCH',
      422,
      'Beneficiary Account Mismatch',
      `Payment was made to '${actualBeneficiary}', which does not match official shop accounts.`,
      'The transfer was sent to an unauthorized recipient. Payments must be sent strictly to Bighabesha Shop official accounts.',
      instance,
      { bank, actualBeneficiary, expectedAccounts }
    );
    this.name = 'BeneficiaryMismatchError';
  }
}

export class AmountMismatchError extends ReceiptVerificationError {
  constructor(expectedAmountEtb: number, actualAmountEtb: number, instance?: string) {
    super(
      'AMOUNT_MISMATCH',
      422,
      'Payment Amount Mismatch',
      `Verified bank payment of ${actualAmountEtb} ETB is less than required order total of ${expectedAmountEtb} ETB.`,
      `The transferred amount (${actualAmountEtb} ETB) is less than the required order total (${expectedAmountEtb} ETB). Please transfer the remaining balance.`,
      instance,
      { expectedAmountEtb, actualAmountEtb, differenceEtb: expectedAmountEtb - actualAmountEtb }
    );
    this.name = 'AmountMismatchError';
  }
}

export class ReceiptExpiredError extends ReceiptVerificationError {
  constructor(orderCreatedAt: Date, txTimestamp: Date, windowMinutes: { before: number; after: number }, instance?: string) {
    super(
      'RECEIPT_EXPIRED',
      422,
      'Receipt Stale or Expired',
      `Transaction timestamp (${txTimestamp.toISOString()}) is outside allowed window around order creation (${orderCreatedAt.toISOString()}).`,
      'The transfer timestamp is outside the valid transaction window. Please complete transfers within 2 hours of checkout.',
      instance,
      { orderCreatedAt: orderCreatedAt.toISOString(), txTimestamp: txTimestamp.toISOString(), windowMinutes }
    );
    this.name = 'ReceiptExpiredError';
  }
}

export class QrDecodeFailedError extends ReceiptVerificationError {
  constructor(reason?: string, instance?: string) {
    super(
      'QR_DECODE_FAILED',
      422,
      'QR Code Matrix Decoding Failed',
      reason || 'Image matrix does not contain a recognizable 2D QR code or the image is too blurry.',
      'Could not read the QR code on the receipt screenshot. Please ensure the image is clear, uncropped, and not blurry, or enter the reference code manually.',
      instance,
      { reason }
    );
    this.name = 'QrDecodeFailedError';
  }
}

export class BankPortalUnavailableError extends ReceiptVerificationError {
  constructor(bank: SupportedBank, reason: string, instance?: string) {
    super(
      'BANK_PORTAL_UNAVAILABLE',
      504,
      'Bank Confirmation Portal Unavailable',
      `Upstream verification portal for ${bank.toUpperCase()} timed out or failed to respond: ${reason}`,
      'The bank confirmation portal is currently unresponsive. Your receipt has been routed to our store administrators for manual review.',
      instance,
      { bank, reason }
    );
    this.name = 'BankPortalUnavailableError';
  }
}

export class PortalGeoblockedError extends ReceiptVerificationError {
  constructor(bank: SupportedBank, proxyHost?: string, instance?: string) {
    super(
      'PORTAL_GEOBLOCKED',
      502,
      'Bank Portal Geoblocked or Proxy Egress Failed',
      `Access to ${bank.toUpperCase()} transaction verification portal was blocked or Ethiopian residential proxy failed.`,
      'Bank gateway routing encountered a regional network block. Receipt routed to administrator review queue for manual verification.',
      instance,
      { bank, proxyHost }
    );
    this.name = 'PortalGeoblockedError';
  }
}

export class UnsupportedBankError extends ReceiptVerificationError {
  constructor(detectedRail: string, instance?: string) {
    super(
      'UNSUPPORTED_BANK',
      400,
      'Unsupported Banking Rail',
      `Automated verification is not currently supported for banking rail: '${detectedRail}'.`,
      'Automated verification currently supports CBE and Telebirr. Other banks will be reviewed manually by administrators.',
      instance,
      { detectedRail }
    );
    this.name = 'UnsupportedBankError';
  }
}

