export type DecodeMethod =
  | 'qr_matrix'
  | 'pdf_stream'
  | 'ocr_regex'
  | 'sms_regex'
  | 'manual_code';

/** Final operational status of the verification pipeline */
export type VerificationStatus =
  | 'auto_verified'
  | 'pending_manual_review'
  | 'rejected'
  | 'upstream_failure';

/** The four discrete security gate pillars evaluated before fulfillment */
export type SecurityPillarId =
  | 'anti_replay'
  | 'beneficiary_whitelist'
  | 'exact_amount'
  | 'recency_window';

/** State of the circuit breaker protecting upstream bank portals */
export type CircuitBreakerState = 'CLOSED' | 'OPEN' | 'HALF_OPEN';

