/** Result of evaluating an individual security pillar */
export interface SecurityPillarEvaluation {
  /** The security pillar evaluated */
  pillar: SecurityPillarId;
  /** Whether this individual pillar assertion passed */
  passed: boolean;
  /** Expected value or constraint definition */
  expected: string | number;
  /** Actual value extracted from bank confirmation */
  actual: string | number;
  /** Human-readable explanation or diagnostic log */
  details?: string;
  /** Allowable variance or tolerance (e.g. in ETB or minutes) */
  tolerance?: number;
}

/** Comprehensive result of the 4-Pillar Security Gate */
export interface SecurityGateResult {
  /** True strictly when ALL four pillars have passed */
  passed: boolean;
  /** Ordered list of evaluations for each of the 4 pillars */
  evaluations: SecurityPillarEvaluation[];
  /** The first failing pillar evaluation if any failed */
  failedPillar?: SecurityPillarEvaluation;
  /** Timestamp when evaluation completed */
  evaluatedAt: Date;
}

/** Minimal order context required by the Security Gate */
export interface OrderSecurityContext {
  /** Unique Order ID */
  orderId: string;
  /** Telegram User ID of the buyer */
  userId: number;
  /** Net payable order amount in ETB after discounts */
  netPayableEtb: number;
  /** Payment rail selected by buyer during checkout */
  paymentRail: SupportedBank;
  /** Order creation timestamp */
  orderCreatedAt: Date;
}

/** Store configuration mapping bank rails to approved beneficiary accounts */
export interface BeneficiaryWhitelistConfig {
  cbe: string[];
  telebirr: string[];
  abyssinia?: string[];
}

/** Temporal recency window configuration */
export interface RecencyWindowConfig {
  /** Maximum minutes prior to order creation that slip timestamp is accepted */
  minutesBefore: number;
  /** Maximum minutes after order creation that slip timestamp is accepted */
  minutesAfter: number;
}

