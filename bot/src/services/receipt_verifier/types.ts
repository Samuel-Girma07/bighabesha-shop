// 7. Core Service Interfaces (Contracts)
// ============================================================================

/**
 * Service responsible for ingesting files/text, image preprocessing,
 * QR matrix decoding via ZXing, and PDF vector stream extraction.
 */
export interface IReceiptIngestionService {
  /**
   * Ingests a raw file buffer (image or PDF) and extracts reference data.
   * Enforces 16MP caps, decompression bomb protection, and multi-pass decoding.
   */
  ingestBuffer(
    buffer: Buffer,
    mimeType: ReceiptMimeType,
    options?: IngestionOptions
  ): Promise<ExtractedReceiptReference>;

  /**
   * Ingests raw SMS or text message and parses bank transaction references via regex.
   */
  ingestText(rawText: string): Promise<ExtractedReceiptReference>;

  /**
   * Dedicated testing harness for QR decoding on uploaded images.
   */
  testQrMatrix(imageBuffer: Buffer): Promise<QrTestResult>;
}

/**
 * Bank Adapter interface. Implemented by CbeBankAdapter and TelebirrAdapter.
 */
export interface IBankReceiptVerifier {
  /** The specific banking rail handled by this adapter */
  readonly bankRail: SupportedBank;

  /** Checks whether this adapter can verify the given extracted reference/URL */
  canHandle(reference: ExtractedReceiptReference): boolean;

  /**
   * Queries upstream bank portal (e.g. CBE Port 100 or Telebirr proxy)
   * and parses confirmation details. Bound to 7.5s abort timeout.
   */
  verify(
    reference: ExtractedReceiptReference,
    options?: BankVerificationOptions
  ): Promise<BankTransactionPayload>;
}

/**
 * Security Gate verifying the 4 critical pillars before order fulfillment.
 */
export interface ISecurityGate {
  /**
   * Evaluates all 4 pillars atomically.
   */
  evaluate(
    order: OrderSecurityContext,
    bankPayload: BankTransactionPayload
  ): Promise<SecurityGateResult>;

  /**
   * Pillar 1: Anti-Replay check against SQLite receipt_evidence unique index.
   */
  assertAntiReplay(
    normalizedReference: string,
    orderId: string
  ): Promise<{ passed: boolean; existingOrderId?: string }>;

  /**
   * Pillar 2: Beneficiary Whitelist check against configured store accounts.
   */
  assertBeneficiary(
    bank: SupportedBank,
    beneficiaryAccount: string
  ): boolean;

  /**
   * Pillar 3: Amount check ensuring verified payment matches or exceeds net order price.
   */
  assertAmount(
    orderAmountEtb: number,
    paidAmountEtb: number,
    toleranceEtb?: number
  ): boolean;

  /**
   * Pillar 4: Recency Window assertion ensuring payment occurred within allowable timeframe.
   */
  assertRecency(
    orderCreatedAt: Date,
    txTimestamp: Date,
    windowMinutes?: RecencyWindowConfig
  ): boolean;
}

/**
 * Central Orchestrator coordinating Ingestion -> Adapter -> Security Gate -> Resolution.
 */
export interface IReceiptOrchestrator {
  /**
   * Ingests, verifies, evaluates security gate, updates order, and fulfills or routes to fallback.
   */
  processSubmission(submission: ReceiptSubmission): Promise<VerificationResult>;

  /**
   * Triggers manual re-verification of an existing order by an administrator.
   */
  reverifyOrder(orderId: string, adminId: number): Promise<VerificationResult>;

  /**
   * Queries the latest audit evidence record for an order.
   */
  getAuditRecord(orderId: string): Promise<VerificationAuditRecord | null>;

  /**
   * Returns a paginated list of verification audit records with filtering.
   */
  queryEvidence(filter: EvidenceQueryFilter): Promise<PaginatedResult<VerificationAuditRecord>>;
}

