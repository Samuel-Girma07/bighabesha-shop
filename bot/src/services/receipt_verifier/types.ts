/** Extracted reference data parsed from QR matrix, vector PDF, or raw text */
export interface ExtractedReceiptReference {
  /** The identified bank rail */
  bank: SupportedBank;
  /** Raw unconverted reference string as extracted from receipt */
  rawReference: string;
  /** Normalized canonical reference string (uppercase, stripped whitespace) */
  normalizedReference: string;
  /** Direct bank confirmation URL if decoded from a QR code */
  sourceUrl?: string;
  /** Transfer amount in ETB if embedded directly in QR payload/SMS */
  amountEtb?: number;
  /** Timestamp when extraction occurred */
  extractedAt: Date;
  /** Confidence score between 0.0 and 1.0 */
  confidence: number;
  /** Method through which extraction was performed */
  decodeMethod: DecodeMethod;
  /** Diagnostic snippet of raw unparsed text or payload */
  rawPayloadSnippet?: string;
  /** Optional bounding box of decoded QR matrix in source image */
  qrBoundingBox?: {
    x: number;
    y: number;
    width: number;
    height: number;
  };
}

/** Configurable tuning parameters for image pre-processing and matrix decoding */
export interface IngestionOptions {
  /** Maximum pixel dimension cap to prevent decompression bombs (default: 16777216) */
  maxPixels?: number;
  /** Whether to apply grayscale and dynamic contrast stretching before decoding */
  enableContrastEnhancement?: boolean;
  /** Try multiple binarization thresholds on low-contrast images */
  multiPassThresholding?: boolean;
  /** Maximum execution timeout in milliseconds for ingestion (default: 5000ms) */
  timeoutMs?: number;
}

/** Diagnostic result returned by the QR test endpoint */
export interface QrTestResult {
  /** Whether a QR matrix was successfully located and decoded */
  success: boolean;
  /** Raw decoded text decoded from the matrix */
  rawText?: string;
  /** Structured reference extracted from the raw QR text */
  extractedReference?: ExtractedReceiptReference;
  /** Total processing duration in milliseconds */
  decodeDurationMs: number;
  /** Number of pre-processing threshold passes attempted */
  passesAttempted: number;
  /** Error description if decoding failed */
  error?: string;
}

